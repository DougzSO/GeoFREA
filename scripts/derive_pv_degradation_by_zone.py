"""Derive the PV degradation rate of each thermal zone T1-T7 from the public fleet data of Jordan et al. (COMMAND 83, Group 3).

usage: python scripts/derive_pv_degradation_by_zone.py [--csv PATH] [--min-systems 20] [--write-parameters] [--audit PATH]

Reads `Fleet_results_public_2022_02_02.csv` (DuraMAT), takes `plr_median` (%/year, negative for a loss; converted to a positive rate), keeps
crystalline-silicon systems in ground mounting when the sample allows it, and computes per `pv_climate_zone` the number of systems, the median
and the mean. A zone with fewer than `--min-systems` systems is pooled with the nearest zone. The result is written to
`docs/_audit/pv_degradation_zones_83.md` and, with `--write-parameters`, to `config/parameters.json` (`solar.degradation_by_zone` of the real
countries; the synthetic country is left alone).

Check: the pooled medians of the coolest and the hottest zones must lie near 0.48 and 0.88 %/year (Jordan et al. 2022); a larger difference than
`--tolerance` (percentage points per year) is reported and the exit code is 2, so F6 is not to be run before the review.
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import UTC, datetime
from pathlib import Path

import pandas as pd

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "src"))

from geofrea.core.pv_zones import derive_zone_rates, zone_degradation_bounds

DEFAULT_CSV = Path("D:/Douglas/DOUTORADO/GeoFREA_data/external/pv_degradation/Fleet_results_public_2022_02_02.csv")
CRYSTALLINE = ("mono-Si", "multi-Si", "c-Si")
GROUND = ("Ground",)
REFERENCE_COOL_PCT = 0.48  # Jordan et al. 2022, cooler climates
REFERENCE_HOT_PCT = 0.88  # Jordan et al. 2022, hotter climates
SOURCE = "Jordan et al. 2022 (DuraMAT public fleet results, Fleet_results_public_2022_02_02.csv)"


def apply_filter(fleet: pd.DataFrame) -> tuple[pd.DataFrame, str]:
    """Crystalline silicon in ground mounting; the description of the filter."""
    keep = fleet["technology1"].isin(CRYSTALLINE) & fleet["type_mounting"].isin(GROUND)
    return fleet[keep], "technology1 in {mono-Si, multi-Si, c-Si} and type_mounting == Ground"


def build_block(fleet: pd.DataFrame, min_systems: int) -> tuple[dict, list, pd.DataFrame, str]:
    """The `degradation_by_zone` block, the derived rates, the table of counts with and without the filter, and the filter text."""
    filtered, filter_text = apply_filter(fleet)
    rates = derive_zone_rates(filtered, min_systems)
    zones = {
        f"T{r.zone}": {
            "n": r.n,
            "median": round(r.median, 6),
            "mean": round(r.mean, 6),
            "merged_with": None if r.merged_with is None else f"T{r.merged_with}",
        }
        for r in rates
    }
    counts = pd.DataFrame(
        {
            "n_all": fleet["pv_climate_zone"].value_counts(),
            "n_filtered": filtered["pv_climate_zone"].value_counts(),
        }
    ).fillna(0).astype(int).sort_index()
    block = {
        "source": SOURCE,
        "tier": 2,
        "filter": filter_text,
        "min_systems": min_systems,
        "generated_date": datetime.now(tz=UTC).date().isoformat(),
        "synthetic": False,
        "zones": zones,
    }
    return block, rates, counts, filter_text


def check_against_reference(rates: list, tolerance_pct: float) -> tuple[bool, str]:
    """Coolest and hottest zone medians (%/year) against the values reported by Jordan et al."""
    cool, hot = rates[0].median * 100.0, rates[-1].median * 100.0
    ok_cool = abs(cool - REFERENCE_COOL_PCT) <= tolerance_pct
    ok_hot = abs(hot - REFERENCE_HOT_PCT) <= tolerance_pct
    text = (
        f"coolest zone median {cool:.3f} %/yr vs {REFERENCE_COOL_PCT} ({'ok' if ok_cool else 'DIVERGES'}); "
        f"hottest zone median {hot:.3f} %/yr vs {REFERENCE_HOT_PCT} ({'ok' if ok_hot else 'DIVERGES'}); tolerance {tolerance_pct} pp"
    )
    return ok_cool and ok_hot, text


def audit_text(block: dict, counts: pd.DataFrame, fleet: pd.DataFrame, check_text: str, ok: bool) -> str:
    lines = [
        "# PV degradation by thermal zone (COMMAND 83)",
        "",
        f"Generated by `scripts/derive_pv_degradation_by_zone.py` on {block['generated_date']}. Source: {block['source']}.",
        f"Filter: {block['filter']}. Minimum systems per zone: {block['min_systems']}. `plr_median` (%/yr, negative for a loss) is converted to a positive rate.",
        f"Rows in the file: {len(fleet)}; with a zone: {int(fleet['pv_climate_zone'].notna().sum())}.",
        "",
        "## Systems per zone, with and without the filter",
        "",
        "| Zone | N all | N filtered |",
        "|---|---|---|",
        *[f"| {z} | {int(r.n_all)} | {int(r.n_filtered)} |" for z, r in counts.iterrows()],
        "",
        (
            "The fleet has no system in T1 and T7 and few in T2: those zones are pooled with the nearest zone, so the rate of T7 is the rate of T6 and the "
            "rate of T1 and T2 is the one of T3."
        ),
        "",
        "## Rates by zone (fractions per year; the sampling range runs from the median to the mean when the mean is higher)",
        "",
        "| Zone | N (pooled) | Median | Mean | Pooled with |",
        "|---|---|---|---|---|",
        *[
            f"| {z} | {v['n']} | {v['median']:.4f} | {v['mean']:.4f} | {v['merged_with'] or '-'} |"
            for z, v in block["zones"].items()
        ],
        "",
        "## Check against Jordan et al. (about 0.48 %/yr cooler, 0.88 %/yr hotter)",
        "",
        check_text,
        "",
        "Result: " + ("passed" if ok else "**FAILED. Report to Douglas; do not run F6.**"),
        "",
    ]
    return "\n".join(lines)


def write_parameters(path: Path, block: dict) -> list[str]:
    """Set `solar.degradation_by_zone` of every country that is not synthetic; returns the countries changed."""
    data = json.loads(path.read_text(encoding="utf-8"))
    changed = []
    for iso, country in data["countries"].items():
        solar = country["technologies"]["solar"]
        if solar.get("synthetic") or (solar.get("capex_usd_per_kw") or {}).get("synthetic"):
            continue
        kept = (solar.get("degradation_by_zone") or {}).get("hot_zone_sensitivity")  # a hand-set sensitivity, not derived from the fleet
        solar["degradation_by_zone"] = {**block, **({"hot_zone_sensitivity": kept} if kept else {})}
        changed.append(iso)
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return changed


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--csv", type=Path, default=DEFAULT_CSV)
    parser.add_argument("--min-systems", type=int, default=20)
    parser.add_argument("--tolerance", type=float, default=0.15, help="percentage points per year")
    parser.add_argument("--audit", type=Path, default=REPO / "docs/_audit/pv_degradation_zones_83.md")
    parser.add_argument("--parameters", type=Path, default=REPO / "config/parameters.json")
    parser.add_argument("--write-parameters", action="store_true")
    args = parser.parse_args(argv)

    if not args.csv.exists():
        print(f"fleet file not found: {args.csv}", file=sys.stderr)
        return 1
    fleet = pd.read_csv(args.csv)
    block, rates, counts, _ = build_block(fleet, args.min_systems)
    ok, check_text = check_against_reference(rates, args.tolerance)
    for z, v in block["zones"].items():
        low, high = zone_degradation_bounds(v)
        print(f"{z}: n={v['n']} median={v['median']:.4f} mean={v['mean']:.4f} range=[{low:.4f}, {high:.4f}] merged_with={v['merged_with']}")
    print(check_text)
    args.audit.write_text(audit_text(block, counts, fleet, check_text, ok), encoding="utf-8")
    if args.write_parameters:
        print("parameters.json updated for:", ", ".join(write_parameters(args.parameters, block)))
    return 0 if ok else 2


if __name__ == "__main__":
    raise SystemExit(main())
